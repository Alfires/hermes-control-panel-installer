#!/usr/bin/env bash
# One-line installer for the Hermes Control Deck.
#
#   curl -fsSL <raw>/install.sh | sudo bash
#
# Root is required because the panel talks to two root-owned brokers (vault and
# host control) over group-restricted unix sockets. Secrets are generated on
# the machine and never printed.
set -euo pipefail

APP_REPO="${APP_REPO:-http://192.168.2.157:3001/Alfires/hermes-control-panel.git}"
APP_REF="${APP_REF:-main}"
INSTALL_DIR="${INSTALL_DIR:-/opt/hermes-control-panel}"
PROTECTED_DIR="${PROTECTED_DIR:-/opt/panel-secrets}"
SOCKET_DIR="${SOCKET_DIR:-/opt/panel-sockets}"
WEBUI_PORT="${WEBUI_PORT:-9120}"
SOCKET_GID="${SOCKET_GID:-1000}"
LLM_ENV="${LLM_ENV:-/home/deck/opencode-api/api.env}"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

log()  { printf '[hermes-deck] %s\n' "$*"; }
fail() { printf '[hermes-deck] ERROR: %s\n' "$*" >&2; exit 1; }

need_cmd() { command -v "$1" >/dev/null 2>&1 || fail "missing command: $1"; }

preflight() {
  [[ $EUID -eq 0 ]] || fail "run as root: curl -fsSL <url>/install.sh | sudo bash"
  need_cmd git
  need_cmd docker
  need_cmd openssl
  need_cmd curl
  docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 plugin is required"
  log "preflight ok (root, docker compose v2, openssl)"
}

fetch_app() {
  if [[ -d "$INSTALL_DIR/.git" ]]; then
    log "updating existing checkout at $INSTALL_DIR"
    git -C "$INSTALL_DIR" fetch --quiet origin "$APP_REF"
    git -C "$INSTALL_DIR" reset --hard --quiet "origin/$APP_REF"
  else
    log "cloning application into $INSTALL_DIR"
    mkdir -p "$(dirname "$INSTALL_DIR")"
    git clone --quiet --depth 1 --branch "$APP_REF" "$APP_REPO" "$INSTALL_DIR"
  fi
  [[ -f "$INSTALL_DIR/docker-compose.yml" ]] || fail "application checkout is incomplete"
}

provision_brokers() {
  mkdir -p "$PROTECTED_DIR" "$SOCKET_DIR"
  chmod 700 "$PROTECTED_DIR"
  chmod 755 "$SOCKET_DIR"

  # Root-only HMAC key: the panel container reads a copy, the broker verifies.
  if [[ ! -s "$PROTECTED_DIR/hostctl.key" ]]; then
    umask 077
    openssl rand -hex 32 >"$PROTECTED_DIR/hostctl.key"
    log "generated root-only host-control key"
  fi
  chmod 600 "$PROTECTED_DIR/hostctl.key"
  [[ -f "$PROTECTED_DIR/critical-packages.json" ]] || printf '{}\n' >"$PROTECTED_DIR/critical-packages.json"
  chmod 600 "$PROTECTED_DIR/critical-packages.json"

  install -o root -g root -m 0644 "$INSTALL_DIR/hostctl/panel-hostctl.service" /etc/systemd/system/panel-hostctl.service
  install -o root -g root -m 0644 "$INSTALL_DIR/hostctl/panel-socket-relay.service" /etc/systemd/system/panel-socket-relay.service
  systemctl daemon-reload
  systemctl enable --now panel-hostctl >/dev/null
  systemctl restart panel-hostctl >/dev/null
  systemctl enable --now panel-socket-relay >/dev/null
  systemctl restart panel-socket-relay >/dev/null

  local i
  for i in $(seq 1 20); do
    [[ -S /run/panel-host.sock && -S "$SOCKET_DIR/hostctl.sock" && -S "$SOCKET_DIR/vault.sock" ]] && break
    sleep 0.5
  done
  [[ -S "$SOCKET_DIR/hostctl.sock" ]] || fail "host-control relay did not start"
  log "brokers: hostctl=$(systemctl is-active panel-hostctl) relay=$(systemctl is-active panel-socket-relay)"
}

write_env() {
  local env_file="$INSTALL_DIR/panel.env"
  local admin_pass model_key

  if [[ -f "$env_file" ]]; then
    log "keeping existing admin password in $env_file"
    admin_pass="$(sed -n 's/^PANEL_ADMIN_PASSWORD=//p' "$env_file" | head -1)"
  else
    admin_pass="$(openssl rand -hex 12)"
  fi

  # Prefer the existing local model front door token when present; otherwise
  # generate one so the file is complete and can be edited later.
  model_key=""
  if [[ -r "$LLM_ENV" ]]; then
    model_key="$(sed -n 's/^OPENCODE_API_TOKEN=//p' "$LLM_ENV" | head -1 | tr -d "\"'\r")"
  fi
  [[ -n "$model_key" ]] || model_key="$(openssl rand -hex 24)"

  umask 077
  cat >"$env_file" <<EOF
# Generated by hermes-control-panel-installer. Key names only are logged.
PANEL_ADMIN_USER=admin
PANEL_ADMIN_PASSWORD=$admin_pass
PANEL_LLM_URL=http://host.docker.internal:4097/v1/chat/completions
PANEL_LLM_KEY=$model_key
HERMES_URL=http://host.docker.internal:8642
HERMES_DASHBOARD_URL=http://host.docker.internal:9119
VAULT_SOCKET=/run/panel-sockets/vault.sock
HOSTCTL_SOCKET=/run/panel-sockets/hostctl.sock
PANEL_HOST_KEY=/run/secrets/hostctl.key
PANEL_SOCKET_GID=$SOCKET_GID
WEBUI_PORT=$WEBUI_PORT
PANEL_DATA=/var/lib/panel
EOF
  chmod 600 "$env_file"
  log "wrote $env_file (chmod 600) with the keys the app actually reads"
}

bring_up() {
  cd "$INSTALL_DIR"
  mkdir -p "$INSTALL_DIR/data"
  chown "$SOCKET_GID:$SOCKET_GID" "$INSTALL_DIR/data"
  chmod 770 "$INSTALL_DIR/data"

  # Only the panel is started. The compose file's gateway service is behind a
  # "standalone" profile; a plain `up` must never open a second 8642/9119.
  docker compose build webui
  docker compose up -d --no-deps webui

  log "waiting for health"
  local i
  for i in $(seq 1 60); do
    if curl -fsS "http://127.0.0.1:${WEBUI_PORT}/health.php" >/dev/null 2>&1; then
      log "panel ready at http://127.0.0.1:${WEBUI_PORT} (login: admin / password in $INSTALL_DIR/panel.env)"
      return 0
    fi
    sleep 2
  done
  fail "panel did not become healthy; inspect: docker compose -f $INSTALL_DIR/docker-compose.yml logs"
}

status() {
  cd "$INSTALL_DIR"
  docker compose ps
}

uninstall() {
  cd "$INSTALL_DIR"
  docker compose stop webui >/dev/null 2>&1 || true
  log "stopped. Data and secrets preserved in $INSTALL_DIR and $PROTECTED_DIR"
}

main() {
  local cmd="${1:-install}"
  case "$cmd" in
    install)   preflight; fetch_app; provision_brokers; write_env; bring_up ;;
    status)    status ;;
    uninstall) uninstall ;;
    *) fail "usage: install.sh [install|status|uninstall]" ;;
  esac
}

main "$@"
