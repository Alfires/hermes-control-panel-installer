#!/usr/bin/env bash
# One-line installer for the Hermes Control Deck.
# curl -fsSL <raw>/install.sh | bash
set -euo pipefail

APP_REPO="http://192.168.2.157:3001/Alfires/hermes-control-panel.git"
APP_REF="${APP_REF:-main}"
INSTALL_DIR="${INSTALL_DIR:-$HOME/.local/hermes-control-panel}"
WEBUI_PORT="${WEBUI_PORT:-9120}"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

log()  { printf '[hermes-deck] %s\n' "$*"; }
fail() { printf '[hermes-deck] ERROR: %s\n' "$*" >&2; exit 1; }

need_cmd() { command -v "$1" >/dev/null 2>&1 || fail "missing command: $1"; }

preflight() {
  need_cmd git
  need_cmd docker
  need_cmd openssl
  docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 plugin is required"
}

write_env() {
  local env_file="$INSTALL_DIR/panel.env"
  if [[ -f "$env_file" ]]; then
    log "keeping existing $env_file"
    return 0
  fi
  umask 077
  local admin_secret panel_secret model_key
  admin_secret="$(openssl rand -hex 32)"
  panel_secret="$(openssl rand -hex 32)"
  model_key="$(openssl rand -hex 32)"
  cat >"$env_file" <<EOF
# Generated by install.sh - key names only are ever logged.
ADMIN_USER=admin
ADMIN_PASSWORD_HASH=
ADMIN_SECRET=$admin_secret
PANEL_SECRET=$panel_secret
MODEL_API_KEY=$model_key
HERMES_URL=http://hermes:8642
HERMES_DASHBOARD_URL=http://hermes:9119
WEBUI_PORT=$WEBUI_PORT
PANEL_DATA=/var/lib/panel
EOF
  chmod 600 "$env_file"
  log "generated secrets in $env_file (chmod 600)"
}

fetch_app() {
  if [[ -d "$INSTALL_DIR/.git" ]]; then
    log "updating existing checkout"
    git -C "$INSTALL_DIR" fetch --quiet origin "$APP_REF"
    git -C "$INSTALL_DIR" reset --hard --quiet "origin/$APP_REF"
  else
    log "cloning application into $INSTALL_DIR"
    mkdir -p "$(dirname "$INSTALL_DIR")"
    git clone --quiet --depth 1 --branch "$APP_REF" "$APP_REPO" "$INSTALL_DIR"
  fi
}

bring_up() {
  cd "$INSTALL_DIR"
  docker compose pull hermes || true
  docker compose build webui
  docker compose up -d
  log "waiting for health"
  local i
  for i in $(seq 1 60); do
    if curl -fsS "http://127.0.0.1:${WEBUI_PORT}/health.php" >/dev/null 2>&1; then
      log "panel ready at http://127.0.0.1:${WEBUI_PORT}"
      return 0
    fi
    sleep 2
  done
  fail "panel did not become healthy; inspect: docker compose logs"
}

status() {
  cd "$INSTALL_DIR"
  docker compose ps
}

uninstall() {
  cd "$INSTALL_DIR"
  docker compose down
  log "stopped. Data preserved in $INSTALL_DIR/data"
}

main() {
  local cmd="${1:-install}"
  case "$cmd" in
    install)   preflight; fetch_app; write_env; bring_up ;;
    status)    status ;;
    uninstall) uninstall ;;
    *) fail "usage: install.sh [install|status|uninstall]" ;;
  esac
}

main "$@"
